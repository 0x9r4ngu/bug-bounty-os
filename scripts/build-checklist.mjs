// Parses the web-pentesting-checklist markdown into a structured template:
// Parts -> Sections (checkable items) with the section body kept as "how to test" markdown.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const src = fs.readFileSync(path.join(__dirname, "checklist-source.md"), "utf8");
const lines = src.split("\n");

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 48);

const parts = [];
let curPart = null;
let curItem = null;
let inFrontmatter = false;
let seenFirstPart = false;

function pushItem() {
  if (curItem && curPart) {
    curItem.body = curItem.bodyLines.join("\n").trim();
    delete curItem.bodyLines;
    curPart.items.push(curItem);
  }
  curItem = null;
}

for (let i = 0; i < lines.length; i++) {
  const line = lines[i];
  if (i === 0 && line.trim() === "---") { inFrontmatter = true; continue; }
  if (inFrontmatter) { if (line.trim() === "---") inFrontmatter = false; continue; }

  const partMatch = /^##\s+(.*)/.exec(line);
  const sectionMatch = /^###\s+(.*)/.exec(line);

  if (partMatch && !sectionMatch) {
    pushItem();
    seenFirstPart = true;
    curPart = { id: `part-${parts.length + 1}`, title: partMatch[1].trim(), items: [] };
    parts.push(curPart);
    continue;
  }
  if (sectionMatch && curPart) {
    pushItem();
    const title = sectionMatch[1].trim();
    const numMatch = /^(\d+)\.?\s+(.*)/.exec(title);
    curItem = {
      key: `${curPart.id}--${slug(title)}`,
      num: numMatch ? numMatch[1] : "",
      title: numMatch ? numMatch[2] : title,
      bodyLines: [],
    };
    continue;
  }
  if (curItem) curItem.bodyLines.push(line);
}
pushItem();

const totalItems = parts.reduce((a, p) => a + p.items.length, 0);
const template = {
  title: "Advanced Web Application Penetration Testing Checklist",
  source: "https://github.com/0x9r4ngu/writeups",
  totalItems,
  parts,
};

const out = `// AUTO-GENERATED by scripts/build-checklist.mjs — do not edit by hand.
// Source: web-pentesting-checklist (0x9r4ngu/writeups)
export interface ChecklistItem { key: string; num: string; title: string; body: string; }
export interface ChecklistPart { id: string; title: string; items: ChecklistItem[]; }
export interface ChecklistTemplate { title: string; source: string; totalItems: number; parts: ChecklistPart[]; }
export const CHECKLIST_TEMPLATE: ChecklistTemplate = ${JSON.stringify(template, null, 2)};
`;

const dest = path.join(__dirname, "..", "client", "src", "lib", "checklist-template.ts");
fs.writeFileSync(dest, out);
console.log(`Wrote ${dest}`);
console.log(`Parts: ${parts.length}  Items: ${totalItems}`);
parts.forEach((p) => console.log(`  ${p.title.padEnd(48)} ${p.items.length} items`));
